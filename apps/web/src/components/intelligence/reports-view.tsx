"use client";

import { ChevronLeft, ChevronRight, FileText, Loader2 } from "lucide-react";
import Link from "next/link";
import { useRouter, useSearchParams } from "next/navigation";
import { useState } from "react";

import { QueryError } from "@/components/common/query-state";
import { PageHeader } from "@/components/layout/page-header";
import { useAlerts, useGenerateReport, useReports } from "@/hooks/use-intelligence";
import { useCountries } from "@/hooks/use-surveillance";
import { diseaseParam, useDisease, useFilters, withParams } from "@/lib/filters";
import { formatInt, formatWeek } from "@/lib/format";
import type { AlertSeverity, AlertType } from "@/lib/types";
import { cn } from "@/lib/utils";

import { ALERT_LABEL, AlertSeverityBadge, AlertTypeLabel, SEVERITY_ORDER, alertText } from "./alert-ui";

type Tab = "alerts" | "reports";
const TYPES = Object.keys(ALERT_LABEL) as AlertType[];

function setParam(key: string, value: string | null) {
  const next = new URLSearchParams(window.location.search);
  if (value) next.set(key, value);
  else next.delete(key);
  window.history.replaceState(null, "", `?${next.toString()}`);
}

export function ReportsView() {
  const params = useSearchParams();
  const [tab, setTab] = useState<Tab>(params.get("tab") === "reports" ? "reports" : "alerts");
  return (
    <div className="flex flex-1 flex-col gap-4 p-4 lg:p-6">
      <PageHeader
        title="Reports & Alerts"
        description="Alerts are generated by fixed rules from stored detection outputs. Reports are deterministic templates over stored facts and can be re-verified."
      />
      <div className="flex gap-1 rounded-full border border-border bg-muted p-1 text-xs sm:w-fit" role="tablist" aria-label="Section">
        {(["alerts", "reports"] as const).map((t) => (
          <button
            key={t}
            type="button"
            role="tab"
            aria-selected={tab === t}
            onClick={() => {
              setTab(t);
              setParam("tab", t === "alerts" ? null : t);
            }}
            className={cn(
              "flex-1 rounded px-4 py-1.5 capitalize transition-colors",
              tab === t ? "bg-primary font-medium text-primary-foreground" : "text-muted-foreground hover:text-foreground",
            )}
          >
            {t}
          </button>
        ))}
      </div>
      {tab === "alerts" ? <AlertsPanel /> : <ReportsPanel />}
    </div>
  );
}

/* ---------- Alerts ---------- */

function Chip({ active, onClick, children }: { active: boolean; onClick: () => void; children: React.ReactNode }) {
  return (
    <button
      type="button"
      aria-pressed={active}
      onClick={onClick}
      className={cn(
        "rounded-full border px-2.5 py-0.5 text-xs transition-colors",
        active ? "border-primary bg-primary/15 text-foreground" : "border-border text-muted-foreground hover:text-foreground",
      )}
    >
      {children}
    </button>
  );
}

function AlertsPanel() {
  const dp = diseaseParam(useDisease());
  const [filters] = useFilters();
  const params = useSearchParams();
  const [type, setType] = useState<AlertType | null>((params.get("type") as AlertType) ?? null);
  const [severity, setSeverity] = useState<AlertSeverity | null>((params.get("severity") as AlertSeverity) ?? null);
  const [status, setStatus] = useState<"active" | "retracted" | "all">("active");
  const [page, setPage] = useState(1);
  const [iso3, setIso3] = useState<string | null>(params.get("iso3")?.toUpperCase() ?? null);
  const q = useAlerts({ region: filters.region, iso3, type, severity, status, page, pageSize: 50 });
  const d = q.data;
  const pages = d ? Math.max(1, Math.ceil(d.total / d.page_size)) : 1;

  return (
    <section className="panel">
      <div className="space-y-2.5 border-b border-border p-4">
        <div className="flex flex-wrap items-center gap-1.5">
          <span className="mr-1 text-[11px] text-muted-foreground">Type</span>
          <Chip active={type == null} onClick={() => { setType(null); setPage(1); setParam("type", null); }}>
            All
          </Chip>
          {TYPES.map((t) => (
            <Chip key={t} active={type === t} onClick={() => { setType(t); setPage(1); setParam("type", t); }}>
              {ALERT_LABEL[t]} <span className="metric text-muted-foreground">{formatInt(d?.by_type[t] ?? 0)}</span>
            </Chip>
          ))}
        </div>
        <div className="flex flex-wrap items-center gap-1.5">
          <span className="mr-1 text-[11px] text-muted-foreground">Severity</span>
          <Chip active={severity == null} onClick={() => { setSeverity(null); setPage(1); setParam("severity", null); }}>
            All
          </Chip>
          {SEVERITY_ORDER.map((s) => (
            <Chip key={s} active={severity === s} onClick={() => { setSeverity(s); setPage(1); setParam("severity", s); }}>
              <span className="capitalize">{s}</span> <span className="metric text-muted-foreground">{formatInt(d?.by_severity[s] ?? 0)}</span>
            </Chip>
          ))}
          <label htmlFor="alert-status" className="ml-auto flex items-center gap-2 text-xs text-muted-foreground">
            Status
            <select
              id="alert-status"
              aria-label="Status"
              value={status}
              onChange={(e) => { setStatus(e.target.value as typeof status); setPage(1); }}
              className="h-7 rounded-md border border-border bg-card px-2 text-foreground"
            >
              <option value="active">Active</option>
              <option value="retracted">Retracted</option>
              <option value="all">All</option>
            </select>
          </label>
        </div>
        {iso3 && (
          <div className="flex items-center gap-1.5">
            <span className="mr-1 text-[11px] text-muted-foreground">Country</span>
            <Chip active onClick={() => { setIso3(null); setPage(1); setParam("iso3", null); }}>
              {d?.items[0]?.name ?? iso3} ×
            </Chip>
          </div>
        )}
        {type && d && <p className="text-[11px] text-muted-foreground">Rule: {d.rules[type]}</p>}
      </div>

      {q.error && <QueryError error={q.error} className="p-4" />}
      {d && d.items.length === 0 && <p className="p-4 text-xs text-muted-foreground">No alerts match these filters.</p>}
      {d && d.items.length > 0 && (
        <div className="overflow-x-auto" tabIndex={0} role="region" aria-label="Alerts table">
          <table className="w-full text-xs">
            <thead className="text-[11px] text-muted-foreground">
              <tr className="border-b border-border">
                <th className="px-4 py-2 text-left font-normal">Week</th>
                <th className="px-2 py-2 text-left font-normal">Country</th>
                <th className="px-2 py-2 text-left font-normal">Type</th>
                <th className="px-2 py-2 text-left font-normal">Severity</th>
                <th className="px-4 py-2 text-left font-normal">Alert</th>
              </tr>
            </thead>
            <tbody>
              {d.items.map((a) => (
                <tr key={a.id} className={cn("border-b border-border/60 last:border-0 hover:bg-accent/40", a.status === "retracted" && "opacity-60")}>
                  <td className="metric whitespace-nowrap px-4 py-2 text-muted-foreground">
                    {formatWeek(a.week_start)}
                    {a.details.provisional === true && <span className="ml-1 text-[10px] text-status-warn">prov.</span>}
                  </td>
                  <td className="whitespace-nowrap px-2 py-2">
                    <Link href={withParams(`/countries/${a.iso3}`, dp)} className="hover:underline">{a.name}</Link>
                  </td>
                  <td className="px-2 py-2"><AlertTypeLabel t={a.alert_type} /></td>
                  <td className="px-2 py-2"><AlertSeverityBadge s={a.severity} /></td>
                  <td className="px-4 py-2 text-muted-foreground">
                    {alertText(a.title, a.name)}
                    {a.status === "retracted" && <span className="ml-1.5 rounded bg-muted px-1 text-[10px]">retracted after a data revision</span>}
                  </td>
                </tr>
              ))}
            </tbody>
          </table>
        </div>
      )}
      {d && d.total > 0 && (
        <div className="flex items-center justify-between border-t border-border px-4 py-2 text-xs text-muted-foreground">
          <span>
            {formatInt(d.total)} alerts{filters.region ? ` in ${filters.region}` : ""} · page {page} of {pages}
          </span>
          <span className="flex gap-1">
            <button type="button" aria-label="Previous page" disabled={page <= 1} onClick={() => setPage((p) => p - 1)}
              className="rounded border border-border p-1 disabled:opacity-40">
              <ChevronLeft className="size-3.5" />
            </button>
            <button type="button" aria-label="Next page" disabled={page >= pages} onClick={() => setPage((p) => p + 1)}
              className="rounded border border-border p-1 disabled:opacity-40">
              <ChevronRight className="size-3.5" />
            </button>
          </span>
        </div>
      )}
    </section>
  );
}

/* ---------- Reports ---------- */

const WEEK_CHOICES = [1, 4, 8, 13, 26];

export function GenerateReportForm({ fixedIso3 }: { fixedIso3?: string }) {
  const [filters] = useFilters();
  const router = useRouter();
  const [scope, setScope] = useState<"global" | "country">(fixedIso3 ? "country" : "global");
  const [iso3, setIso3] = useState(fixedIso3 ?? "");
  const [weeks, setWeeks] = useState(filters.weeks);
  const disease = useDisease();
  const countries = useCountries({ disease, region: null, q: "", sort: "name", order: "asc", page: 1, pageSize: 300 });
  const gen = useGenerateReport();

  const submit = (e: React.FormEvent) => {
    e.preventDefault();
    gen.mutate(
      {
        scope,
        iso3: scope === "country" ? iso3 : null,
        region: scope === "global" ? filters.region : null,
        to: filters.to,
        weeks,
      },
      {
        onSuccess: (r) =>
          router.push(withParams(`/reports/${r.report.id}`, r.reused ? "reused=1" : "", diseaseParam(disease))),
      },
    );
  };

  return (
    <form onSubmit={submit} className="flex flex-wrap items-end gap-3 text-xs">
      {!fixedIso3 && (
        <label className="flex flex-col gap-1">
          <span className="text-muted-foreground">Scope</span>
          <select aria-label="Scope" value={scope} onChange={(e) => setScope(e.target.value as typeof scope)}
            className="h-8 rounded-md border border-border bg-card px-2">
            <option value="global">{filters.region ? `WHO ${filters.region} region` : "Global"}</option>
            <option value="country">One country</option>
          </select>
        </label>
      )}
      {scope === "country" && !fixedIso3 && (
        <label className="flex flex-col gap-1">
          <span className="text-muted-foreground">Country</span>
          <select aria-label="Country" value={iso3} onChange={(e) => setIso3(e.target.value)} required
            className="h-8 w-56 rounded-md border border-border bg-card px-2">
            <option value="">Choose a country…</option>
            {countries.data?.items.filter((c) => c.weeks_reported > 0).map((c) => (
              <option key={c.iso3} value={c.iso3}>{c.name}</option>
            ))}
          </select>
        </label>
      )}
      <label className="flex flex-col gap-1">
        <span className="text-muted-foreground">Period</span>
        <select aria-label="Period" value={weeks} onChange={(e) => setWeeks(Number(e.target.value))}
          className="h-8 rounded-md border border-border bg-card px-2">
          {WEEK_CHOICES.map((w) => (
            <option key={w} value={w}>{w === 1 ? "1 week" : `${w} weeks`}</option>
          ))}
        </select>
      </label>
      <button
        type="submit"
        disabled={gen.isPending || (scope === "country" && !iso3)}
        className="inline-flex h-8 items-center gap-1.5 rounded-md bg-primary px-3 font-medium text-primary-foreground disabled:opacity-50"
      >
        {gen.isPending ? <Loader2 className="size-3.5 animate-spin" /> : <FileText className="size-3.5" />}
        Generate report
      </button>
      <span className="text-[11px] text-muted-foreground">
        Ends {filters.to ? formatWeek(filters.to) : "at the latest settled week"} (period filter in the top bar).
      </span>
      {gen.error && <QueryError error={gen.error} className="w-full text-status-error" />}
    </form>
  );
}

function ReportsPanel() {
  const dp = diseaseParam(useDisease());
  const [page, setPage] = useState(1);
  const q = useReports(page);
  const d = q.data;
  const pages = d ? Math.max(1, Math.ceil(d.total / d.page_size)) : 1;
  return (
    <div className="space-y-4">
      <section className="panel p-4">
        <h2 className="text-sm font-medium">Generate a report</h2>
        <p className="mb-3 mt-0.5 text-[11px] text-muted-foreground">
          Built only from stored data: surveillance, forecasts, risk, anomalies, hotspots and alerts. The same inputs
          always give the same report; an identical existing report is reused.
        </p>
        <GenerateReportForm />
      </section>
      <section className="panel">
        <h2 className="border-b border-border p-4 text-sm font-medium">Reports</h2>
        {q.error && <QueryError error={q.error} className="p-4" />}
        {d && d.items.length === 0 && <p className="p-4 text-xs text-muted-foreground">No reports yet. Generate one above.</p>}
        {d && d.items.length > 0 && (
          <table className="w-full text-xs">
            <thead className="text-[11px] text-muted-foreground">
              <tr className="border-b border-border">
                <th className="px-4 py-2 text-left font-normal">Report</th>
                <th className="px-2 py-2 text-left font-normal">Period</th>
                <th className="px-2 py-2 text-right font-normal">Alerts</th>
                <th className="px-2 py-2 text-left font-normal">Created</th>
                <th className="px-4 py-2 text-left font-normal">Inputs</th>
              </tr>
            </thead>
            <tbody>
              {d.items.map((r) => (
                <tr key={r.id} className="border-b border-border/60 last:border-0 hover:bg-accent/40">
                  <td className="px-4 py-2">
                    <Link href={withParams(`/reports/${r.id}`, dp)} className="hover:underline">{r.title}</Link>
                  </td>
                  <td className="whitespace-nowrap px-2 py-2 text-muted-foreground">
                    {formatWeek(r.period_start)} – {formatWeek(r.period_end)}
                  </td>
                  <td className="metric px-2 py-2 text-right">{r.alerts}</td>
                  <td className="whitespace-nowrap px-2 py-2 text-muted-foreground">
                    {new Date(r.created_at).toLocaleString("en-GB", { dateStyle: "medium", timeStyle: "short" })}
                  </td>
                  <td className="px-4 py-2 font-mono text-[10.5px] text-muted-foreground" title={r.inputs_sha256}>
                    {r.inputs_sha256.slice(0, 12)}
                  </td>
                </tr>
              ))}
            </tbody>
          </table>
        )}
        {d && d.total > d.page_size && (
          <div className="flex items-center justify-end gap-1 border-t border-border px-4 py-2 text-xs">
            <button type="button" aria-label="Previous page" disabled={page <= 1} onClick={() => setPage((p) => p - 1)}
              className="rounded border border-border p-1 disabled:opacity-40"><ChevronLeft className="size-3.5" /></button>
            <button type="button" aria-label="Next page" disabled={page >= pages} onClick={() => setPage((p) => p + 1)}
              className="rounded border border-border p-1 disabled:opacity-40"><ChevronRight className="size-3.5" /></button>
          </div>
        )}
      </section>
    </div>
  );
}
