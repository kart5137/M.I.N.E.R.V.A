"""Profile WHO dengue surveillance per country: grain, completeness and coverage tiers.

Usage (from the repo root):
    .venv/Scripts/python pipeline/scripts/profile_dengue.py [--download]

(requires `pip install -e pipeline`)

Outputs:
    data/profiles/dengue_country_profile.csv   one row per country/area
    docs/datasets/dengue_profile.md            generated report

Uses exactly the cleaning, validation and coverage code of `ei ingest dengue`.
"""

from __future__ import annotations

import argparse
from dataclasses import asdict
from datetime import UTC, date, datetime

import pandas as pd

from ei_pipeline.config import ROOT
from ei_pipeline.quality.coverage import (
    DENGUE_TIERS,
    DENGUE_WINDOW_MONTHS,
    DENGUE_WINDOW_WEEKS,
    analyse_dengue,
)
from ei_pipeline.quality.validation import validate_monthly, validate_weekly
from ei_pipeline.sources import dengue

PROFILE_CSV = ROOT / "data" / "profiles" / "dengue_country_profile.csv"
REPORT_MD = ROOT / "docs" / "datasets" / "dengue_profile.md"


def md_table(df: pd.DataFrame) -> str:
    cols = list(df.columns)
    lines = ["| " + " | ".join(map(str, cols)) + " |", "|" + "---|" * len(cols)]
    for r in df.itertuples(index=False):
        lines.append("| " + " | ".join("" if pd.isna(v) else str(v) for v in r) + " |")
    return "\n".join(lines)


def _checks(rep: dict) -> str:
    rows = [f"| {name} (hard: excluded) | {v['rows']:,} |" for name, v in rep["hard"].items()]
    rows += [f"| {name} (warning only) | {n:,} |" for name, n in rep["soft"].items()]
    return "| Check | Rows |\n|---|---|\n" + "\n".join(rows)


def build_report(raw: pd.DataFrame, cleaned: dengue.Cleaned, weekly: pd.DataFrame,
                 monthly: pd.DataFrame, v_week: dict, v_month: dict, cov) -> str:
    now = datetime.now(UTC).strftime("%Y-%m-%d %H:%M UTC")
    prof = cov.profiles
    rep = cleaned.report
    tier_counts = prof["tier"].value_counts().reindex(list(DENGUE_TIERS), fill_value=0)

    by_region = (
        prof.pivot_table(index="who_region", columns="tier", values="country_code",
                         aggfunc="count", fill_value=0)
        .reindex(columns=list(DENGUE_TIERS), fill_value=0)
        .assign(Total=lambda d: d.sum(axis=1))
        .reset_index().rename(columns={"who_region": "WHO region"})
    )
    raw_grain = raw.groupby("DATE_TYPE")["ISO3"].nunique().rename("areas").reset_index()
    raw_grain = raw_grain.merge(raw["DATE_TYPE"].value_counts().rename("rows").reset_index(),
                                on="DATE_TYPE").rename(columns={"DATE_TYPE": "grain"})

    per_year = pd.concat([
        weekly.assign(year=weekly["week_start"].dt.year, grain="weekly"),
        monthly.assign(year=monthly["month_start"].dt.year, grain="monthly"),
    ]).groupby(["year", "grain"]).agg(areas=("country_code", "nunique"),
                                      reports=("cases", "size"),
                                      cases=("cases", "sum")).reset_index()
    per_year = per_year.pivot(index="year", columns="grain",
                              values=["areas", "reports", "cases"]).fillna(0).astype("int64")
    per_year.columns = [f"{g} {m}" for m, g in per_year.columns]
    per_year = per_year.reset_index()

    mixed = prof[prof["has_weekly"] & prof["has_monthly"]][
        ["country_code", "country_name", "grain", "first_period", "last_period", "tier"]]
    mixed = mixed.assign(first_period=mixed["first_period"].dt.date,
                         last_period=mixed["last_period"].dt.date)

    show = ["country_code", "country_name", "who_region", "grain", "window_completeness",
            "window_longest_gap", "weeks_since_last_report", "median_cases",
            "share_zero_case_periods"]

    def tier_table(t: str) -> str:
        sub = prof[prof["tier"] == t].sort_values(["who_region", "country_name"])[show]
        return md_table(sub) if len(sub) else "_None._"

    neg_cleared = " / ".join(f"{rep.negative_extra_values_cleared.get(k, 0):,}"
                             for k in dengue.EXTRA_COUNTS)
    years = pd.concat([weekly["week_start"], monthly["month_start"]]).dt.year
    prov_w = ", ".join(f"{d.date()} ({n})" for d, n in cov.provisional_weeks.items()) or "none"
    prov_m = ", ".join(f"{d.date()} ({n})" for d, n in cov.provisional_months.items()) or "none"

    return f"""# WHO dengue coverage profile (generated)

> Generated by `pipeline/scripts/profile_dengue.py` on {now}. Do not edit by hand;
> re-run the script. Source description and rules: [dengue.md](dengue.md).

## Snapshot

- Raw rows: **{rep.raw_rows:,}** → loaded: **{len(weekly):,}** country-weeks and
  **{len(monthly):,}** country-months
- Countries/areas: **{prof['country_code'].nunique()}** · years with data:
  **{int(years.min())}–{int(years.max())}**
- Weekly reference week (last week with ≥ 80% of the typical number of reporting
  countries): **{cov.reference_week.date()}**. Provisional weeks after it
  (reporting countries): {prov_w}
- Monthly reference month: **{cov.reference_month.date() if cov.reference_month is not None
                              else "n/a"}**. Provisional months: {prov_m}
- Coverage window: **{DENGUE_WINDOW_WEEKS} weeks / {DENGUE_WINDOW_MONTHS} months** ending at
  the reference period. A "reported" period is one with a case value (0 counts).
- Share of loaded periods with zero cases: weekly
  **{(weekly['cases'] == 0).mean():.0%}**, monthly **{(monthly['cases'] == 0).mean():.0%}**

### Grains in the raw export

{md_table(raw_grain)}

## Coverage tiers

Each area is profiled in the grain of its most recent report. Monthly reporters cannot
be forecast weekly, so they are tier C at best.

| Tier | Areas | Rule |
|---|---|---|
""" + "\n".join(f"| {t} | {tier_counts[t]} | {DENGUE_TIERS[t]} |" for t in DENGUE_TIERS) + f"""

### By WHO region

{md_table(by_region)}

### Areas reporting at both grains

Both series are stored (weekly in `surveillance_weekly`, monthly in
`surveillance_monthly`); the area is shown in its primary grain.

{md_table(mixed) if len(mixed) else "_None._"}

## Cleaning actions

| Action | Rows |
|---|---|
| Exact duplicate rows dropped | {rep.exact_duplicates_dropped:,} |
| Unknown `DATE_TYPE` dropped | {rep.unknown_date_type_dropped:,} |
| Missing `START_DATE` rebuilt from `YEAR`/`DATE_NUM` | {rep.start_date_rebuilt:,} |
| Start date unrecoverable (impossible period label), dropped | {rep.start_date_unrecoverable:,} |
| `START_DATE` disagreeing with `YEAR`/`DATE_NUM` | {rep.period_label_mismatch:,} |
| No case value, dropped (not a report) | {rep.no_case_value_dropped:,} |
| … of which empty future placeholders | {rep.no_case_value_future_placeholders:,} |
| Negative confirmed / severe / death values cleared | {neg_cleared} |
| Epi-weeks (Sunday start) mapped to the next-day ISO week | {rep.epiweeks_mapped_to_iso:,} |
| Epi-week dropped: same Monday also has an ISO week | {rep.overlapping_epi_iso_weeks_dropped:,} |

## Validation

Weekly rows ({v_week['rows_in']:,} in, {v_week['rows_excluded']:,} excluded):

{_checks(v_week)}

Monthly rows ({v_month['rows_in']:,} in, {v_month['rows_excluded']:,} excluded):

{_checks(v_month)}

## Reporting over time

{md_table(per_year)}

## Tier A — forecast-ready (weekly)

{tier_table("A")}

## Tier B — forecast with caution (weekly)

{tier_table("B")}

## Tier C — map and trends only

{tier_table("C")}

## Tier D — historical only

{tier_table("D")}
"""


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--download", action="store_true", help="re-download the WHO CSV first")
    args = ap.parse_args()
    if args.download or not dengue.RAW_PATH.exists():
        print(f"Downloading WHO dengue → {dengue.RAW_PATH}")
        dengue.download(dengue.RAW_PATH)

    today = date.today()
    raw = dengue.load_raw(dengue.RAW_PATH)
    cleaned = dengue.clean(raw, today=today)
    weekly, v_week = validate_weekly(cleaned.weekly, today=today, count_cols=("cases",),
                                     soft=dengue.soft_checks(cleaned.weekly))
    monthly, v_month = validate_monthly(cleaned.monthly, today=today,
                                        soft=dengue.soft_checks(cleaned.monthly))
    cov = analyse_dengue(weekly, monthly)

    PROFILE_CSV.parent.mkdir(parents=True, exist_ok=True)
    cov.profiles.to_csv(PROFILE_CSV, index=False)
    REPORT_MD.write_text(build_report(raw, cleaned, weekly, monthly, v_week, v_month, cov),
                         encoding="utf-8", newline="\n")
    print(cov.profiles["tier"].value_counts().sort_index().to_string())
    print(asdict(cleaned.report)["notes"] or "no cleaning notes")
    print(f"Wrote {PROFILE_CSV.relative_to(ROOT)} and {REPORT_MD.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
